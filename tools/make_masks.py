"""스프라이트 알파를 저조해상도 마스크로 변환 (클릭 판정용). assets/characters/masks.js 생성."""
import glob, json, os
import numpy as np
from PIL import Image
D = os.path.join(os.path.dirname(__file__), "..", "assets", "characters")
COLS = 56
out = {}
for f in sorted(glob.glob(os.path.join(D, "*_*.png"))):
    key = os.path.basename(f)[:-4]
    a = np.asarray(Image.open(f).convert("RGBA"))[:, :, 3] / 255.0
    h, w = a.shape
    rows = max(1, round(COLS * h / w))
    im = Image.fromarray((a * 255).astype("uint8")).resize((COLS, rows), Image.BILINEAR)
    m = np.asarray(im) > 60
    out[key] = {"w": w, "h": h, "cols": COLS, "rows": rows, "data": ["".join("1" if v else "0" for v in r) for r in m]}
with open(os.path.join(D, "masks.js"), "w") as fp:
    fp.write("// generated by tools/make_masks.py\nexport default " + json.dumps(out) + ";\n")
print(len(out), "masks")
